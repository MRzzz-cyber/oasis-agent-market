import { UsdcBudgetLedger } from "../../policy/src/usdc.mjs";

/**
 * Trusted coordinator between autonomous purchase intents and a payment transport.
 * The transport must be separately reviewed x402 SDK integration.
 * No wallet or signer is provided to the LLM.
 */
export class PurchaseCoordinator {
  constructor({ policy, transport, ledger = new UsdcBudgetLedger(policy) }) {
    if (!policy || !(ledger instanceof UsdcBudgetLedger)) throw new TypeError("USDC policy and ledger are required");
    if (ledger.policy !== policy) throw new Error("Ledger/policy mismatch");
    this.policy = policy;
    this.ledger = ledger;
    this.transport = transport;
  }

  async purchase(quote, { now = Date.now() } = {}) {
    const reservation = this.ledger.reserve(quote, now);
    if (!reservation.allowed) return { status: "blocked", reasons: reservation.reasons, quoteId: quote?.quoteId ?? null };

    if (!this.transport || typeof this.transport.pay !== "function") {
      this.ledger.fail(quote.quoteId, { submitted: false });
      return { status: "blocked", reasons: ["Payment transport is not configured"], quoteId: quote.quoteId };
    }

    let submitted = false;
    try {
      // The transport is trusted application code, never generated by an LLM.
      // Its pay method must use a reviewed SDK and verify the settlement.
      submitted = true;
      const result = await this.transport.pay({ ...quote });
      if (!result || result.settled !== true || result.verified !== true ||
        result.quoteId !== quote.quoteId ||
        result.network !== this.policy.network ||
        String(result.asset).toLowerCase() !== this.policy.asset.toLowerCase() ||
        String(result.payTo).toLowerCase() !== quote.payTo.toLowerCase() ||
        result.amountAtomic !== quote.amountAtomic) {
        this.ledger.fail(quote.quoteId, { submitted: true });
        return { status: "reconciliation_required", reasons: ["Unverified or mismatched payment settlement"], quoteId: quote.quoteId };
      }
      const record = this.ledger.settle(quote.quoteId, result.transactionHash);
      return {
        status: "settled",
        quoteId: quote.quoteId,
        payment: { transactionHash: record.transactionHash, network: this.policy.network },
        data: result.data ?? null,
        ledger: this.ledger.getSnapshot()
      };
    } catch (error) {
      // Network errors cannot prove that no payment was submitted.
      this.ledger.fail(quote.quoteId, { submitted });
      return {
        status: submitted ? "reconciliation_required" : "failed",
        quoteId: quote.quoteId,
        reasons: [String(error?.message || error)]
      };
    }
  }
}
